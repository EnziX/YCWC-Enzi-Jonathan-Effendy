/**
 * Get foods filtered by dietary tags.
 * @param {string[]} allowedTags  – tags the food MUST have (e.g. ['halal','vegetarian'])
 * @param {string[]} excludedTags – tags the food must NOT have (e.g. ['contains-lactose'])
 * @returns {object[]}
 */
export function filterFoodsByTags(allowedTags = [], excludedTags = []) {
  return foodDatabase.filter((food) => {
    const hasRequired = allowedTags.every((tag) => food.tags.includes(tag));
    const hasExcluded = excludedTags.some((tag) => food.tags.includes(tag));
    return hasRequired && !hasExcluded;
  });
}

/**
 * Get foods suitable for a specific meal slot.
 * @param {'breakfast'|'lunch'|'dinner'|'snack'} mealType
 * @returns {object[]}
 */
export function getFoodsByMeal(mealType) {
  return foodDatabase.filter((food) => food.meals.includes(mealType));
}

/**
 * Look up a single food by its ID.
 * @param {string} id
 * @returns {object|undefined}
 */
export function getFoodById(id) {
  return foodDatabase.find((food) => food.id === id);
}
